        private static MetaspriteAsset Sprites()
        {
            MetaspriteAsset asset = new MetaspriteAsset { Prefix = "sc_" };
            asset.Metasprites.Add(new Metasprite
            {
                Name = "ship",
                OriginX = 8,
                OriginY = 8,
                Tiles =
                {
                    new MetaspriteTile { X = 0, Y = 0, Tile = 1 },
                    new MetaspriteTile { X = 8, Y = 0, Tile = 2, FlipH = true },
                },
            });
            asset.Metasprites.Add(new Metasprite
            {
                Name = "star",
                Tiles = { new MetaspriteTile { Tile = 3, Palette = 1, Behind = true, FlipV = true } },
            });
            asset.Animations.Add(new MetaspriteAnimation
            {
                Name = "twinkle",
                Loop = true,
                Frames = { new AnimationFrame { Metasprite = "star", Duration = 8 }, new AnimationFrame { Metasprite = "ship", Duration = 4 } },
            });
            return asset;
        }

        [TestMethod]
        public void TheMetaspriteSourceIsExactly()
        {
            string expected =
                "; Generated by WinASM65.Graphics from game.msprite.json - do not edit\n"
                + "\n"
                + "sc_ship:\n"
                + "        .byte $F8, $01, $00, $F8\n"
                + "        .byte $F8, $02, $40, $00\n"
                + "        .byte $80\n"
                + "\n"
                + "sc_star:\n"
                + "        .byte $00, $03, $A1, $00\n"
                + "        .byte $80\n"
                + "\n"
                + "sc_metasprites_lo:\n"
                + "        .lobytes sc_ship, sc_star\n"
                + "sc_metasprites_hi:\n"
                + "        .hibytes sc_ship, sc_star\n"
                + "\n"
                + "SC_MS_SHIP = 0\n"
                + "SC_MS_STAR = 1\n"
                + "SC_METASPRITE_COUNT = 2\n"
                + "\n"
                + "sc_twinkle_anim:\n"
                + "        .byte 1, 8\n"
                + "        .byte 0, 4\n"
                + "        .byte $FF, 1\n";

            Assert.AreEqual(expected, AssetExporter.MetaspriteSource(Sprites(), "game.msprite.json"));
        }

        [TestMethod]
        public void TheMetaspriteSourceAssembles()
        {
            using (TempFolder folder = new TempFolder())
            {
                string path = folder.File("game.msprite.json");
                Sprites().Save(path);

                ExportResult result = AssetExporter.Export(path);

                Assert.IsFalse(result.HasErrors, TestKit.Describe(result.Diagnostics));
                byte[] bytes = TestKit.Assemble(folder.Path, "game.msprite.asm", " .byte SC_MS_STAR, SC_METASPRITE_COUNT");
                Assert.AreEqual(
                    "F8 01 00 F8 F8 02 40 00 80 "   // ship at $8000
                    + "00 03 A1 00 80 "             // star at $8009
                    + "00 09 80 80 "                // address tables
                    + "01 08 00 04 FF 01 "          // twinkle
                    + "01 02",
                    TestKit.Hex(bytes));
            }
        }

