        [TestMethod]
        public void ExportsAreDeterministicAndAnAssetWithErrorsExportsNothing()
        {
            using (TempFolder folder = new TempFolder())
            {
                TestKit.Palettes().Save(folder.File("a.pal.json"));
                PaletteAsset broken = TestKit.Palettes();
                broken.Palettes.RemoveAt(7);
                broken.Save(folder.File("b.pal.json"));

                ExportResult first = AssetExporter.ExportAll(folder.Path);
                string text = File.ReadAllText(folder.File("a.pal.asm"));
                ExportResult second = AssetExporter.ExportAll(folder.Path);

                Assert.IsTrue(first.HasErrors);
                Assert.AreEqual(2, first.Written.Count, "only a.pal.json exports");
                Assert.IsFalse(File.Exists(folder.File("b.pal.asm")));
                Assert.AreEqual(text, File.ReadAllText(folder.File("a.pal.asm")));
                CollectionAssert.AreEqual(first.Written, second.Written);
            }
        }

        [TestMethod]
        public void NamesBecomeSnakeCaseLabels()
        {
            Assert.AreEqual("ship_left", AsmNames.Snake("Ship Left"));
            Assert.AreEqual("ship_left", AsmNames.Snake("shipLeft"));
            Assert.AreEqual("ship_left", AsmNames.Snake("ship-left"));
            Assert.AreEqual("http_server2", AsmNames.Snake("HTTPServer2"));
            Assert.AreEqual("_1up", AsmNames.Snake("1up"));
            Assert.AreEqual("gm_ship", AsmNames.Label("gm_", "Ship"));
            Assert.AreEqual("GM_MS_SHIP", AsmNames.Constant("gm_", "ms_ship"));
        }
