        [TestMethod]
        public void AttributesArePackedFourBlocksToAByteAndTheLastRowIsHalf()
        {
            ScreenAsset screen = ScreenAsset.Blank(TestKit.Nes, "title");
            screen.Attributes[0] = 1;            // block 0,0: top left of byte 0
            screen.Attributes[1] = 2;            // block 1,0: top right
            screen.Attributes[16] = 3;           // block 0,1: bottom left
            screen.Attributes[16 + 3] = 2;       // block 3,1: bottom right of byte 1
            screen.Attributes[14 * 16 + 0] = 2;  // the last block row: top halves of the last byte row
            screen.Attributes[14 * 16 + 1] = 3;
            screen.Attributes[14 * 16 + 15] = 1;
            screen.Tiles[0] = 7;
            screen.Tiles[959] = 9;

            byte[] table = AssetExporter.ScreenBinary(screen);

            Assert.AreEqual(1024, table.Length);
            Assert.AreEqual(7, table[0]);
            Assert.AreEqual(9, table[959]);
            Assert.AreEqual(0x39, table[960], "1 | 2<<2 | 3<<4");
            Assert.AreEqual(0x80, table[961], "2<<6");
            Assert.AreEqual(0x0E, table[960 + 56], "2 | 3<<2, and nothing below the screen");
            Assert.AreEqual(0x04, table[960 + 63], "block 15,14 is the top right of the last byte");
            for (int i = 962; i < 960 + 56; i++)
                Assert.AreEqual(0, table[i], "attribute byte " + (i - 960));
        }

        [TestMethod]
        public void RleRoundTrips()
        {
            List<byte> data = new List<byte>();
            data.AddRange(Enumerable.Repeat((byte)0, 300));
            data.AddRange(new byte[] { 1, 2, 3, 3, 3, 0xFF });
            data.AddRange(Enumerable.Repeat((byte)0x24, 255));
            byte[] encoded = Rle.Encode(data.ToArray());

            Assert.AreEqual("FF 00 2D 00 01 01 01 02 03 03 01 FF FF 24 00", TestKit.Hex(encoded));
            CollectionAssert.AreEqual(data.ToArray(), Rle.Decode(encoded));
            CollectionAssert.AreEqual(new byte[0], Rle.Decode(Rle.Encode(new byte[0])));
            Assert.ThrowsException<InvalidDataException>(() => Rle.Decode(new byte[] { 3, 1 }));
        }

        [TestMethod]
        public void AScreenExportsItsNametableAndASourceThatIncludesIt()
        {
            using (TempFolder folder = new TempFolder())
            {
                ScreenAsset screen = ScreenAsset.Blank(TestKit.Nes, "Title Screen");
                screen.Tiles[33] = 5;
                screen.Attributes[0] = 3;
                string path = folder.File("title.screen.json");
                screen.Save(path);

                ExportResult result = AssetExporter.Export(path);

                Assert.IsFalse(result.HasErrors, TestKit.Describe(result.Diagnostics));
                byte[] nam = File.ReadAllBytes(folder.File("title.nam"));
                Assert.AreEqual(1024, nam.Length);
                StringAssert.Contains(File.ReadAllText(folder.File("title.screen.asm")), "title_screen:\n        .incbin \"title.nam\"\n\nTITLE_SCREEN_SIZE = 1024\n");
                byte[] bytes = TestKit.Assemble(folder.Path, "title.screen.asm", " .word TITLE_SCREEN_SIZE");
                CollectionAssert.AreEqual(nam.Concat(new byte[] { 0x00, 0x04 }).ToArray(), bytes);
            }
        }

        [TestMethod]
        public void AnRleScreenExportsTheCompressedData()
        {
            using (TempFolder folder = new TempFolder())
            {
                ScreenAsset screen = ScreenAsset.Blank(TestKit.Nes, "title");
                screen.Compression = ScreenAsset.CompressionRle;
                screen.Tiles[100] = 1;
                string path = folder.File("title.screen.json");
                screen.Save(path);

                ExportResult result = AssetExporter.Export(path);

                Assert.IsFalse(result.HasErrors, TestKit.Describe(result.Diagnostics));
                byte[] rle = File.ReadAllBytes(folder.File("title.rle"));
                Assert.IsFalse(File.Exists(folder.File("title.nam")));
                CollectionAssert.AreEqual(TestKit.Nes.EncodeScreen(screen.Tiles, screen.Attributes), Rle.Decode(rle));
                byte[] bytes = TestKit.Assemble(folder.Path, "title.screen.asm", " .byte TITLE_SIZE");
                CollectionAssert.AreEqual(rle.Concat(new[] { (byte)rle.Length }).ToArray(), bytes);
            }
        }

