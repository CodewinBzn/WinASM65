        [TestMethod]
        public void ThePaletteBinaryIsPaletteRamInOrder()
        {
            byte[] ram = AssetExporter.PaletteBinary(TestKit.Palettes());
            Assert.AreEqual(32, ram.Length);
            Assert.AreEqual("21 30 16 28 30 16 28 30 0F 11 21 31 0F 07 17 27 0F 30 11 16 0F 28 38 30 0F 07 17 27 0F 27 37 30", TestKit.Hex(ram));
        }

        [TestMethod]
        public void ThePaletteSourceAssemblesToTheBinary()
        {
            using (TempFolder folder = new TempFolder())
            {
                PaletteAsset palette = TestKit.Palettes();
                palette.Prefix = "gm_";
                palette.Palettes[0].Name = "Title Text";
                string path = folder.File("game.pal.json");
                palette.Save(path);

                ExportResult result = AssetExporter.Export(path);

                Assert.IsFalse(result.HasErrors, TestKit.Describe(result.Diagnostics));
                CollectionAssert.AreEqual(new[] { folder.File("game.pal.bin"), folder.File("game.pal.asm") }, result.Written);
                byte[] binary = File.ReadAllBytes(folder.File("game.pal.bin"));
                string source = File.ReadAllText(folder.File("game.pal.asm"));
                StringAssert.StartsWith(source, "; Generated by WinASM65.Graphics from game.pal.json - do not edit\n");
                StringAssert.Contains(source, "\ngm_palettes:\n        .byte $21, $30, $16, $28 ; background 0: Title Text\n");
                StringAssert.Contains(source, "GM_PAL_TITLE_TEXT = 0\n");
                StringAssert.Contains(source, "GM_PAL_SPRITE3 = 7\n");

                byte[] assembled = TestKit.Assemble(folder.Path, "game.pal.asm", " .byte GM_PAL_TITLE_TEXT, GM_PAL_SPRITE0\n .word gm_palettes");
                CollectionAssert.AreEqual(binary.Concat(new byte[] { 0, 4, 0x00, 0x80 }).ToArray(), assembled);
            }
        }

