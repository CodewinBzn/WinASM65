using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace WinASM65.Graphics.Export
{
    /// <summary>
    /// Builds a generated source: the header, labels, data rows and constants, in
    /// the layout of the hand-written examples (8-space indentation), with <c>\n</c>
    /// line endings whatever the platform so the output is the same everywhere.
    /// </summary>
    internal sealed class AsmWriter
    {
        private const string Indent = "        ";

        private readonly StringBuilder _text = new StringBuilder();

        public AsmWriter(string sourceName)
        {
            _text.Append("; Generated by WinASM65.Graphics from ").Append(sourceName).Append(" - do not edit\n");
        }

        public void Blank()
        {
            _text.Append('\n');
        }

        public void Comment(string comment)
        {
            _text.Append("; ").Append(comment).Append('\n');
        }

        public void Label(string label)
        {
            _text.Append(label).Append(":\n");
        }

        /// <summary>One <c>.byte</c> row of hexadecimal values, with an optional comment.</summary>
        public void HexBytes(IEnumerable<int> values, string comment = null)
        {
            List<string> items = new List<string>();
            foreach (int value in values)
                items.Add(Hex(value));
            Directive(".byte", items, comment);
        }

        /// <summary>One <c>.byte</c> row of decimal values.</summary>
        public void DecimalBytes(IEnumerable<int> values, string comment = null)
        {
            List<string> items = new List<string>();
            foreach (int value in values)
                items.Add(value.ToString(CultureInfo.InvariantCulture));
            Directive(".byte", items, comment);
        }

        /// <summary>Rows of at most <paramref name="perRow"/> decimal values.</summary>
        public void DecimalByteRows(IList<int> values, int perRow)
        {
            for (int start = 0; start < values.Count; start += perRow)
            {
                List<int> row = new List<int>();
                for (int i = start; i < values.Count && i < start + perRow; i++)
                    row.Add(values[i]);
                DecimalBytes(row);
            }
        }

        public void Directive(string directive, IEnumerable<string> arguments, string comment = null)
        {
            _text.Append(Indent).Append(directive);
            string joined = string.Join(", ", arguments);
            if (joined.Length > 0)
                _text.Append(' ').Append(joined);
            if (!string.IsNullOrEmpty(comment))
                _text.Append(" ; ").Append(comment);
            _text.Append('\n');
        }

        public void Constant(string name, int value)
        {
            _text.Append(name).Append(" = ").Append(value.ToString(CultureInfo.InvariantCulture)).Append('\n');
        }

        public static string Hex(int value)
        {
            return "$" + (value & 0xFF).ToString("X2", CultureInfo.InvariantCulture);
        }

        public override string ToString()
        {
            return _text.ToString();
        }
    }
}
